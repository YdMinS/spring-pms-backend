    /** D13: the row group whose Coupang name equals {@code coupangGroup} with every whitespace removed. */
    public static Optional<Group> find(String coupangGroup) {
        if (coupangGroup == null || coupangGroup.isBlank()) {
            return Optional.empty();
        }
        String key = compact(coupangGroup);
        return GROUPS.stream().filter(group -> compact(group.coupangGroup()).equals(key)).findFirst();
    }

    /** D58 · D62 ④: the row group a LotteON item group code is read into ({@code 38} → 「기타 재화」). */
    public static Optional<Group> findByItemGroup(String itemGroupCode) {
        if (itemGroupCode == null) {
            return Optional.empty();
        }
        if (ETC_GROUP_CODE.equals(itemGroupCode)) {
            return find(ETC_IMPORT_GROUP);
        }
        return GROUPS.stream().filter(group -> group.itemGroupCode().equals(itemGroupCode)).findFirst();
    }

    /** D63: the §2-11 item group with this code. */
    public static Optional<OwnGroup> findOwn(String itemGroupCode) {
        if (itemGroupCode == null) {
            return Optional.empty();
        }
        return OWN_GROUPS.stream().filter(group -> group.itemGroupCode().equals(itemGroupCode.trim())).findFirst();
    }

    /** Whitespace-free comparison key (11st D89 ① ②). */
    public static String compact(String value) {
        return value == null ? "" : value.replaceAll("\\s", "");
    }

