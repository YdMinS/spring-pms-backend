    /** D16: the row group whose Coupang name equals {@code coupangGroup} with every whitespace removed. */
    public static Optional<Group> find(String coupangGroup) {
        if (coupangGroup == null || coupangGroup.isBlank()) {
            return Optional.empty();
        }
        String key = compact(coupangGroup);
        return GROUPS.stream().filter(group -> compact(group.coupangGroup()).equals(key)).findFirst();
    }

    /** Whitespace-free comparison key. */
    public static String compact(String value) {
        return value == null ? "" : value.replaceAll("\\s", "");
    }

    private static Group group(String coupangGroup, String groupNo, String groupName, Row... rows) {
        return new Group(coupangGroup, groupNo, groupName, List.of(rows));
    }

