package com.pms.domain;

/**
 * 알림의 출처 (FEATURE_2609_51 / PLAN D1).
 *
 * <p>🔴 알림은 저장되지 않는다 — 이 enum 은 응답에서 <b>행이 어느 업무인지</b>를 말하는 구분자이고,
 * 클라이언트의 이동 목적지(D9)를 가른다. 항목이 늘면 여기에 값을 추가하고 피드 조립부에 한 줄을 더한다.
 *
 * <p>🔴 <b>선언 순서가 목록의 정렬 기준</b>이다(D12) — 같은 시각에 들어온 건들의 순서를
 * {@code 발생시각 desc · 종류 asc(enum 순서) · id desc} 로 고정하는 데 쓰인다. 값을 <b>사이에 끼워 넣으면</b>
 * 이미 나간 커서가 가리키는 위치가 바뀌어 장 경계에서 행이 겹치거나 샌다 — 새 값은 <b>뒤에</b> 붙인다.
 */
public enum AlertType {
    ORDER,
    CLAIM,
    INQUIRY
}
